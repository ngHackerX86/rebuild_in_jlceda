def via_drill_text(points: list[tuple[float, float, float]], *,
                   version: str = EASYEDA_VERSION, ts: str | None = None) -> str:
    """只用过孔生成 `Drill_PTH_Through_Via.DRL`（嘉立创EDA 的包里固定有这一份）。"""
    if not points:
        return ""
    dias = sorted({round(d, 4) for _x, _y, d in points})
    idx = {d: i for i, d in enumerate(dias, 1)}
    out = [";TYPE=PLATED",
           ";Layer: PTH_Through_Via",
           f";EasyEDA Pro v{version}, {ts or now_ts()}",
           f";Gerber Generator version {EASYEDA_GENERATOR}",
           "M48",
           "METRIC,LZ,0000.00000"]
    for d in dias:
        out.append(f";Hole size {idx[d]} = {d:.5f} METRIC")
        out.append(f"T{idx[d]:02d}C{d:.5f}")
    out += ["%", "G05", "G90"]
    cur = None
    for x, y, d in sorted(points, key=lambda t: (idx[round(t[2], 4)], t[1], t[0])):
        t = idx[round(d, 4)]
        if t != cur:
            out.append(f"T{t:02d}")
            cur = t
        out.append(f"X{_fmt(f'{x:.6f}')}Y{_fmt(f'{y:.6f}')}")
    out.append("M30")
    return "\n".join(out) + "\n"


def sidecar_text(board: str, when: str, entries: list[str], report, gate) -> str:
    """zip **外面**的人读说明（内容不进包，保持包内与嘉立创EDA 一致）。"""
    size = "见 Gerber"
    if report is not None and getattr(report, "outline_box", None):
        b = report.outline_box
        size = f"{b[2] - b[0]:.2f} × {b[3] - b[1]:.2f} mm"
    lines = [f"板名：{board}", f"生成：{when}", ""]
    lines.append("包内文件：")
    lines += [f"  {e}" for e in entries]
    lines += ["",
              f"板框尺寸：{size}",
              f"最小线宽/间距：{report.rules['min_trace_mm'] if report else '见工艺页'} mm",
              f"最小孔径：{report.rules['min_hole_mm'] if report else '见工艺页'} mm",
              ""]
    if gate is not None:
        lines.append("发布判定：" + ("允许发布" if gate.publishable else "禁止发布（诊断包）"))
        for st in gate.stages:
            lines.append(f"  [{st.status}] {st.name}" + (f" — {st.detail}" if st.detail else ""))
        for b in gate.blockers:
            lines.append(f"  阻断：{b}")
    lines += ["", f"包内 {JLC_README_NAME} 与嘉立创EDA 导出原文逐字节一致（94 字节）。"]
    return "\n".join(lines) + "\n"


def _check_no_vendor(text: str, name: str) -> None:
    low = text.lower()
    for k in _KICAD_MARKERS:
        if k in low:
            raise RuntimeError(f"{name} 仍含 KiCad 字段 {k!r}，拒绝打包")


def build(files: dict[str, str], drills: list[tuple[str, bool]],
          out_zip: str, board: str, report=None,
          extras: list[tuple[str, str]] | None = None,
          make_note: bool = True, x2_hints: bool = False,
          gdd_path: str | None = None, via_text: str | None = None,
          easyeda_version: str = EASYEDA_VERSION,
          easyeda_ts: str | None = None) -> NativePackage:
    """`files`: {规范层名: 出图文件路径}；`drills`: [(路径, 是否镀通)]。"""
    os.makedirs(os.path.dirname(os.path.abspath(out_zip)) or ".", exist_ok=True)
    today = _dt.date.today().isoformat()
    if not out_zip.lower().endswith(".zip"):
        out_zip += ".zip"
    if not os.path.basename(out_zip).startswith("Gerber_PCB_"):
        out_zip = os.path.join(os.path.dirname(os.path.abspath(out_zip)),
                               f"Gerber_PCB_{board}_{today}.zip")

    copper_total = sum(1 for c in files if c.endswith(".Cu"))
    ts = easyeda_ts or now_ts()
    stamp = _dt.datetime.strptime(ts, "%Y-%m-%d %H:%M:%S").timetuple()[:6]
    assert stamp[5] == int(ts[-2:]), "时间戳秒必须一致"
    tmp = out_zip + ".part"
    pkg = NativePackage(zip_path=out_zip)
    manifest_files: dict[str, str] = {}

    pending: list[tuple[str, bytes]] = []

    def add(entry: str, text: str) -> None:
        _check_no_vendor(text, entry)
        data = text.encode("utf-8")
        pending.append((entry, data))
        manifest_files[entry] = hashlib.sha256(data).hexdigest()

    for canonical, path in files.items():
        named = easyeda_name(canonical)
        if named is None:
            continue
        label, ext = named
        entry = f"Gerber_{label}{ext}"
        text = strip_gerber(open(path, encoding="utf-8", errors="replace").read(),
                            label, version=easyeda_version, ts=ts)
        if x2_hints:
            fn = file_function(canonical, copper_total)
            if fn:
                attr = f"%TF.FileFunction,{fn}*%\n%TF.FilePolarity,Positive*%\n"
                i = text.find("%FS")
                text = text[:i] + attr + text[i:] if i >= 0 else attr + text
        add(entry, text)

    for path, plated in drills:
        label = "PTH_Through" if plated else "NPTH_Through"
        entry = f"Drill_{label}.DRL"
        text = strip_excellon(open(path, encoding="utf-8", errors="replace").read(),
                              plated, label, version=easyeda_version, ts=ts)
        if not text:
            continue
        if x2_hints:
            fn = ("Plated" if plated else "NonPlated") + f",1,{copper_total},PTH"
            text = f"; #@! TF.FileFunction,{fn}\n" + text
        add(entry, text)

    if via_text:
        add("Drill_PTH_Through_Via.DRL", via_text)

    if gdd_path and os.path.isfile(gdd_path):
        gdd = strip_gerber(open(gdd_path, encoding="utf-8", errors="replace").read(),
                           "DrillDrawingLayer", version=easyeda_version, ts=ts)
        add("Gerber_DrillDrawingLayer.GDD", gdd)

    for name, src in (extras or []):
        add(name, open(src, encoding="utf-8", errors="replace").read())

    if make_note:
        pending.append((JLC_README_NAME, JLC_README_BYTES))

    # 条目顺序照嘉立创EDA：顶层/底层/丝印/阻焊/钢网/板框/文档层/内层/GDD/钻孔/JSON/说明
    order = ["Gerber_TopLayer.GTL", "Gerber_BottomLayer.GBL",
             "Gerber_TopSilkscreenLayer.GTO", "Gerber_BottomSilkscreenLayer.GBO",
             "Gerber_TopSolderMaskLayer.GTS", "Gerber_BottomSolderMaskLayer.GBS",
             "Gerber_TopPasteMaskLayer.GTP", "Gerber_BottomPasteMaskLayer.GBP",
             "Gerber_BoardOutlineLayer.GKO", "Gerber_DocumentLayer.GDL"]

    def sort_key(item):
        name = item[0]
        if name in order:
            return (order.index(name), 0)
        if name.startswith("Gerber_InnerLayer"):
            n = int(re.sub(r"\D", "", name) or 1)
            return (order.index("Gerber_DocumentLayer.GDL") + 1, n)
        if name == "Gerber_DrillDrawingLayer.GDD":
            return (100, 0)
        if name.startswith("Drill_"):
            seq = ["Drill_PTH_Through.DRL", "Drill_PTH_Through_Via.DRL",
                   "Drill_NPTH_Through.DRL"]  # NPTH 排最后（EasyEDA 也放在末尾）
            return (200, seq.index(name) if name in seq else 9)
        if name.endswith(".json"):
            return (300, 0)
        return (400, 0)

    pending.sort(key=sort_key)

    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        for entry, data in pending:
            zi = zipfile.ZipInfo(entry, date_time=stamp)   # 与头部时间一致
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.create_system = 0
            zi.external_attr = 0
            with z.open(zi, "w") as fh:
                fh.write(data)
            pkg.entries.append(entry)

    with zipfile.ZipFile(tmp) as z:
        got = [i.filename for i in z.infolist()]
    if got != pkg.entries:
        os.remove(tmp)
        raise RuntimeError(f"打包校验失败：{got}")

    _zero_external_attrs(tmp)
    os.replace(tmp, out_zip)
    pkg.report = {
        "board": board,
        "generated_at": ts,
        "easyeda_version": easyeda_version,
        "zip": os.path.basename(out_zip),
        "entries": pkg.entries,
        "sha256": manifest_files,
    }
    return pkg
