def file_function(canonical: str, copper_total: int) -> str | None:
    if canonical in _FILE_FUNCTION:
        return _FILE_FUNCTION[canonical].format(n=copper_total)
    m = re.fullmatch(r"In(\d+)\.Cu", canonical)
    if m:
        return f"Copper,L{int(m.group(1)) + 1},Inr"
    return None


_KICAD_MARKERS = ("kicad", "pcbnew", "eagle", "altium")
_EASYEDA_MARKERS = ("easyeda", "lceda", "嘉立创eda", "gerber generator version 0.3")

# 需要整行丢弃的 Gerber 行
_GERBER_DROP_PREFIX = ("%TF", "%TA", "%TO", "%TD", "%TO.", "%TA.")
_GERBER_DROP_G04 = ("#@!", "APERTURE LIST", "APERTURE END LIST")


def easyeda_name(canonical: str) -> tuple[str, str] | None:
    """F.Cu -> ('TopLayer', '.GTL')；内层 In<n>.Cu -> ('InnerLayer<n>', '.G<n>')。"""
    if canonical in EASYEDA_LAYERS:
        return EASYEDA_LAYERS[canonical]
    m = re.fullmatch(r"In(\d+)\.Cu", canonical)
    if m:
        return (f"InnerLayer{m.group(1)}", f".G{m.group(1)}")
    return None


def now_ts() -> str:
    return _dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S")


# ------------------------------------------------------------------ Gerber


def looks_like_easyeda(text: str) -> bool:
    """判断一份文件是否本来就是嘉立创EDA 导出的（看头部注释）。"""
    head = "\n".join(text.splitlines()[:12]).lower()
    return any(m in head for m in _EASYEDA_MARKERS)


_NUM_IN_ADD = re.compile(r"(?<=[,X])(-?\d+\.\d+)(?=[X*])")


def _trim_num(raw: str) -> str:
    """0.200000 -> 0.2；1.700000 -> 1.7（嘉立创EDA 用最短写法）。"""
    if "." not in raw:
        return raw
    out = raw.rstrip("0").rstrip(".")
    return out if out not in ("", "-") else "0"


def _normalize_add(line: str) -> str:
    return _NUM_IN_ADD.sub(lambda m: _trim_num(m.group(1)), line)


def easyeda_gerber_header(layer_label: str, copper_areas: int,
                          version: str = EASYEDA_VERSION,
                          ts: str | None = None) -> list[str]:
    return [
        f"G04 Layer: {layer_label}*",
        f"G04 EasyEDA Pro v{version}, {ts or now_ts()}*",
        f"G04 Gerber Generator version {EASYEDA_GENERATOR}*",
        "G04 Scale: 100 percent, Rotated: No, Reflected: No*",
        "G04 Dimensions in millimeters*",
        "G04 Leading zeros omitted, absolute positions, 4 integers and 5 decimals*",
        "G04 Generated by one-click*",
        f"G04 Object Configs: {EASYEDA_OBJECT_CONFIGS}*",
        f"G04 Layer Configs: {EASYEDA_LAYER_CONFIGS}*",
        f"G04 Copper Areas: {copper_areas}*",
    ]


def strip_gerber(text: str, layer_label: str, *, version: str = EASYEDA_VERSION,
                 ts: str | None = None, copper_areas: int | None = None) -> str:
    """重写成嘉立创EDA 的 Gerber 格式（头部、孔径写法、顺序），几何原样保留。"""
    if looks_like_easyeda(text):
        check_gerber_structure(text, layer_label)
        return text if text.endswith("\n") else text + "\n"

    raw_lines = [ln.strip() for ln in text.replace("\r\n", "\n").split("\n")]

    # `%AM…%` 是**多行块**：必须整块搬运，否则宏变空壳、用到该宏的焊盘整批消失
    blocks: list[str] = []
    i = 0
    while i < len(raw_lines):
        t = raw_lines[i]
        if not t:
            i += 1
            continue
        if t.startswith("%") and not t.endswith("%"):
            buf = t
            while i + 1 < len(raw_lines):
                i += 1
                nxt = raw_lines[i]
                if not nxt:
                    continue
                buf += nxt
                if nxt.endswith("%"):
                    break
            blocks.append(buf)
        else:
            blocks.append(t)
        i += 1

    head: list[str] = []          # %FS / %MO
    macros: list[str] = []        # %AM…%
    apertures: list[str] = []     # %ADD…
    body: list[str] = []          # 其余（含 %LPD/%LPC、G75、坐标）
    has_clear = False

    for t in blocks:
        low = t.lower()
        if t.startswith(_GERBER_DROP_PREFIX):
            continue
        if t.startswith("G04"):
            b = t[3:].strip().rstrip("*").strip()
            if any(k in low for k in _KICAD_MARKERS):
                continue
            if any(b.upper().startswith(k) for k in _GERBER_DROP_G04):
                continue
            continue              # 原文件的注记不带，头部统一由我们按 EasyEDA 写
        if t.startswith("%AM"):
            macros.append(t)
        elif t.startswith("%ADD"):
            apertures.append(_normalize_add(t))
        elif t.startswith("%FS") or t.startswith("%MO"):
            head.append(t)
        else:
            if t.startswith("%LPC"):
                has_clear = True
            body.append(t)

    if not has_clear:
        body = [b for b in body if not b.startswith("%LPD")]

    if copper_areas is None:
        copper_areas = sum(1 for b in body if b.startswith("G36"))

    out = "\n".join(
        easyeda_gerber_header(layer_label, copper_areas, version, ts)
        + head + macros + apertures + annotate_sections(body)) + "\n"
    check_gerber_structure(out, layer_label)
    return out


_AM_NAME = re.compile(r"^%AM([^*%]+)")
_AD_REF = re.compile(r"^%ADD\d+([A-Za-z_][A-Za-z0-9_.]*)")


def check_gerber_structure(text: str, label: str) -> None:
    """结构自检：被 %ADD 引用的宏必须有完整定义（防"宏被拆散→焊盘消失"）。"""
    defined = set()
    for line in text.splitlines():
        m = _AM_NAME.match(line.strip())
        if m:
            name = m.group(1).strip()
            body = line.split("*", 1)[1] if "*" in line else ""
            if not body.strip("%* \t"):
                raise RuntimeError(f"{label}: 宏 {name} 定义为空（%AM 块被拆散）")
            defined.add(name)
    standard = {"C", "R", "O", "P"}
    for line in text.splitlines():
        m = _AD_REF.match(line.strip())
        if not m or m.group(1) in standard:
            continue
        if m.group(1) not in defined:
            raise RuntimeError(f"{label}: %ADD 引用了未定义的宏 {m.group(1)}")
    stray = [ln for ln in text.splitlines() if ln[:1].isdigit() and "$" in ln]
    if stray:
        raise RuntimeError(f"{label}: 宏图元散落到图形区（{len(stray)} 行）")


_SECTION_NAME = {"flash": "Pad", "draw": "Track", "region": "Copper"}


def annotate_sections(body: list[str]) -> list[str]:
    """按对象类型补 `G04 Pad/Track/Copper Start|End*` 分区注释（EasyEDA 的写法）。

    纯注释，不改变几何；`G36…G37` 内部不插入任何东西。
    """
    out: list[str] = []
    cur = None                      # 当前分区类型
    in_region = False
    copper_open = False
    for line in body:
        t = line.strip()
        if t.startswith("G36"):
            if cur:
                out.append(f"G04 {_SECTION_NAME[cur]} End*")
                cur = None
            if not copper_open:                 # 整份文件只开一次 Copper 分区
                out.append("G04 Copper Start*")
                copper_open = True
            out.append(line)
            in_region = True
            continue
        if t.startswith("G37"):
            out.append(line)
            in_region = False
            continue
        if in_region:
            out.append(line)
            continue

        if t.endswith("D03*"):
            kind = "flash"
        elif t.endswith("D01*") or t.endswith("D02*"):
            kind = "draw"
        else:
            out.append(line)
            continue

        if kind != cur:
            if cur:
                out.append(f"G04 {_SECTION_NAME[cur]} End*")
            out.append(f"G04 {_SECTION_NAME[kind]} Start*")
            cur = kind
        out.append(line)
    if cur:
        out.append(f"G04 {_SECTION_NAME[cur]} End*")
    if copper_open:
        out.append("G04 Copper End*")
    return out


# ------------------------------------------------------------------ Excellon

_COORD_RE = re.compile(r"^(-?)(\d*)(?:\.(\d*))?$")


def _fmt(v: str) -> str:
    """最短写法，至少 1 位小数（嘉立创EDA：`X0.0Y22.0`、`X0.00002Y-21.99959`）。"""
    m = _COORD_RE.match(v.strip())
    if not m:
        return v
    sign, integer, frac = m.group(1), m.group(2) or "0", (m.group(3) or "")
    frac = frac.rstrip("0") or "0"
    return f"{sign}{integer}.{frac}"


def _fmt_xy(s: str) -> str:
    s = re.sub(r"X(-?[\d.]+)", lambda m: "X" + _fmt(m.group(1)), s)
    s = re.sub(r"Y(-?[\d.]+)", lambda m: "Y" + _fmt(m.group(1)), s)
    return s


def strip_excellon(text: str, plated: bool, layer_label: str, *,
                   version: str = EASYEDA_VERSION, ts: str | None = None) -> str:
    """重写成嘉立创EDA 的钻孔格式；若输入本身就是 EasyEDA 的则原样透传。"""
    if looks_like_easyeda(text):
        return text if text.endswith("\n") else text + "\n"

    tools: list[tuple[str, float]] = []
    body: list[tuple[str, str]] = []
    for raw in text.replace("\r\n", "\n").split("\n"):
        s = raw.strip()
        if not s:
            continue
        low = s.lower()
        if s.startswith(";"):
            continue
        if any(k in low for k in _KICAD_MARKERS):
            continue
        if s.upper() in ("M48", "%", "FMAT,2", "G90", "G05", "M30", "M00"):
            continue                      # 头/尾统一由我们写
        m = re.match(r"^T(\d+)C([\d.]+)$", s, re.I)
        if m:
            tools.append((m.group(1), float(m.group(2))))
            continue
        if re.match(r"^(METRIC|INCH)", s, re.I):
            continue
        if re.match(r"^T\d+$", s, re.I):
            body.append(("TOOL", s[1:]))
            continue
        body.append(("CODE", _fmt_xy(s)))

    if not tools:
        return ""

    mapping = {old: f"{i:02d}" for i, (old, _d) in enumerate(tools, 1)}
    out = [";TYPE=" + ("PLATED" if plated else "NONPLATED"),
           f";Layer: {layer_label}",
           f";EasyEDA Pro v{version}, {ts or now_ts()}",
           f";Gerber Generator version {EASYEDA_GENERATOR}",
           "M48",
           "METRIC,LZ,0000.00000"]
    for i, (_old, dia) in enumerate(tools, 1):
        out.append(f";Hole size {i} = {dia:.5f} METRIC")
        out.append(f"T{i:02d}C{dia:.5f}")
    out += ["%", "G05", "G90"]
    out += _slots_to_g85(body, mapping)
    out.append("M30")
    return "\n".join(out) + "\n"


_ROUTE_MOVE = re.compile(r"^G0?0X([-+]?[\d.]+)Y([-+]?[\d.]+)$", re.I)
_ROUTE_CUT = re.compile(r"^G0?1X([-+]?[\d.]+)Y([-+]?[\d.]+)$", re.I)


def _slots_to_g85(body: list[tuple[str, str]], mapping: dict[str, str]) -> list[str]:
    """铣槽段（G00/M15/G01/M16）压成 G85 槽孔，几何逐点一致。"""
    out: list[str] = []
    start = None
    for kind, val in body:
        if kind == "TOOL":
            out.append("T" + mapping.get(val, val))
            continue
        t = val.strip()
        m = _ROUTE_MOVE.match(t)
        if m:
            start = (m.group(1), m.group(2))
            continue
        if t.upper() == "M15":
            continue
        m = _ROUTE_CUT.match(t)
        if m and start is not None:
            out.append("X{0}Y{1}G85X{2}Y{3}".format(start[0], start[1],
                                                     _fmt(m.group(1)), _fmt(m.group(2))))
            start = None
            continue
        if t.upper() == "M16":
            start = None
            continue
        out.append(t)
    return out


def _zero_external_attrs(path: str) -> None:
    """把 zip 中央目录的 external_attr 归零（与嘉立创EDA 的包一致）。"""
    import struct

    with open(path, "r+b") as fh:
        data = fh.read()
        eocd = data.rfind(b"PK\x05\x06")
        if eocd < 0:
            return
        count = struct.unpack("<H", data[eocd + 10:eocd + 12])[0]
        pos = struct.unpack("<I", data[eocd + 16:eocd + 20])[0]
        for _ in range(count):
            if data[pos:pos + 4] != b"PK\x01\x02":
                return
            fh.seek(pos + 38)
            fh.write(b"\x00\x00\x00\x00")
            name_len, extra_len, comment_len = struct.unpack("<HHH", data[pos + 28:pos + 34])
            pos += 46 + name_len + extra_len + comment_len


