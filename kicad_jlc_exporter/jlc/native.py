"""把 KiCad 出图重写成嘉立创EDA 导出的**同一种文格式**（本地实验用途）。

输出与 `jlc_gerber*` 里的真实 EasyEDA 导出逐行对齐：

    G04 Layer: <层名>*
    G04 EasyEDA Pro v<版本>, <YYYY-MM-DD HH:MM:SS>*
    G04 Gerber Generator version 0.3*
    G04 Scale: 100 percent, Rotated: No, Reflected: No*
    G04 Dimensions in millimeters*
    G04 Leading zeros omitted, absolute positions, 4 integers and 5 decimals*
    G04 Generated by one-click*
    G04 Object Configs: …
    G04 Layer Configs: …
    G04 Copper Areas: <N>*
    %FSLAX45Y45*%
    %MOMM*%
    …

钻孔侧同样是 EasyEDA 方言：`;TYPE=` / `;Layer:` / `;EasyEDA Pro v…` /
`;Gerber Generator version 0.3` / `M48` / `METRIC,LZ,0000.00000` / `;Hole size n = …` /
`T01C…` / `%` / `G05` / `G90` / 数据 / `M30`。

几何一律从 KiCad 原样搬过来，不做布尔运算、不改坐标；只做"同一格式"的重排与数值写法。
`%LPD/%LPC` 属于几何语义（明暗极性），必须成对保留。
"""
from __future__ import annotations

import datetime as _dt
import hashlib
import os
import re
import zipfile
from dataclasses import dataclass, field

